#!/bin/sh
# recovery.sh — the sandbox's other entry point: a shell, not the harness.
#
# Why it exists: when dsh cannot start (broken profile, missing dependency, a
# half-applied update, a rootfs that ran out of space) the app's Web UI is a
# blank page, and the terminal that would let you fix it is a *panel inside that
# Web UI*. The user is locked out of the one tool that could get them back in.
# This script is the way back: the app can boot the guest straight into an SSH
# daemon plus the PTY endpoint, with no harness involved.
#
# Two ways in, both alive at once:
#
#   ssh      full PTY, works from a PC on the same Wi-Fi, from a terminal app on
#            the phone, or over USB after `adb forward tcp:8022 tcp:8022`.
#            Authentication is a *live* token: a fresh random secret generated by
#            the app every time recovery mode starts, used as root's password
#            only for as long as this process runs (see the `trap` below).
#   pty      the app's own on-phone console (a WebView page served by
#            pty-server.mjs), for when the phone is all you have.
#
# Contract with the app (all optional except the token):
#
#   DSH_RECOVERY_TOKEN   root's password for this session (required)
#   DSH_RECOVERY_PORT    sshd port                     (default 8022)
#   DSH_RECOVERY_BIND    sshd listen address           (default 0.0.0.0)
#   DSH_PTY_*            same variables start-dsh.sh uses; the on-phone console
#                        is skipped when DSH_PTY_TOKEN is unset
#
# Readiness is announced on stdout with a line the app parses:
#
#   dsh-recovery: ready port=<n> bind=<addr> user=root token-sha256=<8 hex>
#
# The token itself is never printed: this log is shown in the app's console and
# copied into bug reports. The digest is enough to confirm that the panel and
# the running sshd agree on which secret is live.
set -eu

DSH_HOME="${HOME:-/root}"
DSH_INSTALL="${DSH_INSTALL:-/opt/dsh}"
PORT="${DSH_RECOVERY_PORT:-8022}"
BIND="${DSH_RECOVERY_BIND:-0.0.0.0}"
TOKEN="${DSH_RECOVERY_TOKEN:-}"

# State that must outlive a payload update lives under the bind-mounted home,
# not in the rootfs: /root survives, the rootfs is replaced whole. Host keys in
# particular must be per-device — the ones baked into the payload are the same
# on every install, which makes them useless as an identity.
RECOVERY_DIR="$DSH_HOME/.dsh-recovery"
HOST_KEY="$RECOVERY_DIR/ssh/host_ed25519"
CONFIG="$RECOVERY_DIR/sshd_config"
AUTHORIZED="$RECOVERY_DIR/authorized_keys"

say() { echo "dsh-recovery: $*"; }
die() { echo "dsh-recovery: $*" >&2; exit 1; }

command -v sshd >/dev/null 2>&1 || [ -x /usr/sbin/sshd ] || die "没有 sshd（这个 rootfs 里未安装 openssh-server）"
SSHD="$(command -v sshd 2>/dev/null || echo /usr/sbin/sshd)"

# ---------------------------------------------------------------- token check
# The token becomes a password and a line in /etc/shadow; a colon or a newline
# would corrupt the entry, and an empty one would make root passwordless.
if [ -z "$TOKEN" ]; then
  die "DSH_RECOVERY_TOKEN 为空 —— 恢复模式拒绝以无密码方式启动 sshd"
fi
# Same alphabet the app mints (base64url, no padding), and the same rule the app
# checks before it gets here (RecoveryPlan.validToken) — a colon or a newline
# would corrupt the /etc/shadow line this token is written into. One glob covers
# every character class at once, and unlike a multi-line pattern it is valid in
# dash, which is what /bin/sh is on this rootfs.
case "$TOKEN" in
  *[!A-Za-z0-9_-]*) die "DSH_RECOVERY_TOKEN 含有 base64url 之外的字符（只能是 A-Z a-z 0-9 _ -）" ;;
esac
if [ "${#TOKEN}" -lt 8 ] || [ "${#TOKEN}" -gt 128 ]; then
  die "DSH_RECOVERY_TOKEN 长度必须在 8-128 之间（当前 ${#TOKEN}）"
fi
case "$PORT" in
  ''|*[!0-9]*) die "DSH_RECOVERY_PORT 不是数字：$PORT" ;;
esac
if [ "$PORT" -lt 1024 ] || [ "$PORT" -gt 65535 ]; then
  die "DSH_RECOVERY_PORT 超出范围（1024-65535）：$PORT"
fi

# ------------------------------------------------------------------- ssh keys
mkdir -p "$RECOVERY_DIR/ssh"
chmod 700 "$RECOVERY_DIR" "$RECOVERY_DIR/ssh"
if [ ! -s "$HOST_KEY" ]; then
  say "生成这台设备自己的 SSH 主机密钥（只做一次，之后一直复用）"
  # -q so the fingerprint art does not land in the app's log; the key must not be
  # shared between devices, which is exactly what a payload-baked key would be.
  ssh-keygen -q -t ed25519 -N '' -C "dsh-android-recovery" -f "$HOST_KEY" \
    || die "ssh-keygen 生成主机密钥失败"
fi
chmod 600 "$HOST_KEY"
[ -f "$AUTHORIZED" ] || : > "$AUTHORIZED"
chmod 600 "$AUTHORIZED"

# -------------------------------------------------------------------- password
# Set root's password to the live token, and put it back to a locked value when
# this process ends: the window in which the token is valid is exactly the
# lifetime of the recovery session.
lock_root_password() {
  printf 'root:*\n' | chpasswd -e 2>/dev/null || true
}
# Traps only run between commands, so a signal arriving while sshd owns the
# foreground is *not* acted on until sshd exits — which it never does. The fix is
# to keep sshd in the background and wait for it: `wait` is interrupted by a
# signal, so the handler runs immediately. It also exits explicitly, because dash
# otherwise continues with the next command after a TERM handler.
#
# Everything runs from the EXIT trap, which every path reaches (a signal, sshd
# exiting, the diagnosis branch being killed). Children have to be killed by
# hand: a backgrounded sshd is not part of the shell's job control here and would
# simply be reparented and keep serving after the script is gone.
cleanup() {
  if [ -n "${sshd_pid:-}" ]; then kill "$sshd_pid" 2>/dev/null || true; fi
  if [ -n "${PTY_PID:-}" ]; then kill "$PTY_PID" 2>/dev/null || true; fi
  lock_root_password
}
trap 'cleanup' EXIT
trap 'exit 0' INT TERM HUP
printf 'root:%s\n' "$TOKEN" | chpasswd || die "chpasswd 设置 root 密码失败"

# --------------------------------------------------------------------- sshd
# Privilege separation needs its scratch dir; the payload's rootfs has no /run.
mkdir -p /run/sshd 2>/dev/null || true
chmod 755 /run/sshd 2>/dev/null || true

cat > "$CONFIG" <<EOF
# Written by recovery.sh on every start — do not edit, it is overwritten.
Port $PORT
ListenAddress $BIND
HostKey $HOST_KEY
PidFile $RECOVERY_DIR/sshd.pid

PermitRootLogin yes
PasswordAuthentication yes
PubkeyAuthentication yes
PermitEmptyPasswords no
UsePAM no
AuthorizedKeysFile .ssh/authorized_keys $AUTHORIZED
# The guest is a fake root on a filesystem the platform refuses to chown
# properly (see docs/FINDINGS.md §12): strict mode would reject every file it
# is asked to read a key or a home directory from.
StrictModes no

# Port forwarding is the point of the "tunnel" half of recovery mode: an
# "ssh -p 8022 -L 3080:127.0.0.1:3080 root@<phone>" session lets a PC browser
# drive the harness even when the phone's own WebView cannot render it. Keep
# backticks out of this heredoc: it is unquoted (so $PORT and friends expand),
# and dash parses backticks here as command substitution — which cost one
# "Syntax error: end of file unexpected" that bash -n happily accepted.
AllowTcpForwarding yes
AllowAgentForwarding no
GatewayPorts no
PermitTunnel no
X11Forwarding no

UseDNS no
PrintMotd no
Subsystem sftp internal-sftp
LogLevel INFO
MaxSessions 10
MaxStartups 10:30:60
LoginGraceTime 60
ClientAliveInterval 30
ClientAliveCountMax 6
EOF
chmod 600 "$CONFIG"

# Fail loudly here rather than letting sshd flap every few seconds below: a bad
# option or a missing host key is a configuration bug, not a transient error.
if ! "$SSHD" -t -f "$CONFIG" 2>&1 | sed 's/^/dsh-recovery: /'; then
  die "sshd 配置校验失败（上面一行是原因）"
fi

# ------------------------------------------------------- on-phone console (pty)
# Started before sshd and kept in the background. It is what makes recovery
# possible with nothing but the phone: the app points its WebView at
# http://127.0.0.1:<pty port>/recovery?token=… and gets a line-mode shell.
PTY_PID=""
if [ -n "${DSH_PTY_TOKEN:-}" ] && [ -x "${NODE:-$(command -v node || echo /usr/local/bin/node)}" ]; then
  NODE_BIN="${NODE:-$(command -v node || echo /usr/local/bin/node)}"
  say "启动手机内控制台 127.0.0.1:${DSH_PTY_PORT:-3099}"
  DSH_PTY_PORT="${DSH_PTY_PORT:-3099}" \
  DSH_PTY_TOKEN="$DSH_PTY_TOKEN" \
  DSH_PTY_SHELL="${DSH_PTY_SHELL:-/bin/bash}" \
  "$NODE_BIN" "$DSH_INSTALL/android/pty-server.mjs" >>"$DSH_HOME/.dsh-pty.log" 2>&1 &
  PTY_PID=$!
else
  say "未启用手机内控制台（DSH_PTY_TOKEN 或 node 缺失）"
fi

# ------------------------------------------------------------------ announce
DIGEST="$(printf '%s' "$TOKEN" | sha256sum | cut -c1-8)"
if [ "$PTY_PID" != "" ]; then
  say "pty pid=$PTY_PID"
fi
say "=============================================="
say " 恢复模式：harness 没有启动，这里是一个真 shell"
say " 用户 root · 密码 = 应用面板上显示的恢复令牌"
say " 同一 Wi-Fi：   ssh -p $PORT root@<手机局域网 IP>"
say " USB：          adb forward tcp:$PORT tcp:$PORT"
say "                ssh -p $PORT root@127.0.0.1"
say " 端口转发（从电脑用浏览器打开 harness）："
say "                ssh -p $PORT -L 3080:127.0.0.1:3080 root@<IP>"
say " 修好之后回应用点「退出恢复模式」即可正常启动"
say "=============================================="
say "ready port=$PORT bind=$BIND user=root token-sha256=$DIGEST"

# --------------------------------------------------------------------- serve
# Foreground: the PRoot process must stay alive for as long as recovery is on,
# and --kill-on-exit is what tears the whole tree down when the user stops it.
# A few retries cover the one realistic transient failure (the port still being
# held by the previous instance); after that we stay up and keep the diagnosis
# on screen instead of exiting into a restart loop.
attempt=0
while :; do
  attempt=$((attempt + 1))
  started=$(date +%s)
  set +e
  # Backgrounded on purpose: see the trap comment above. `wait` returns on the
  # child's exit *or* on a signal, which is what makes stopping recovery either
  # way (clean exit or TERM) end with root's password locked again.
  "$SSHD" -D -e -f "$CONFIG" &
  sshd_pid=$!
  wait "$sshd_pid"
  code=$?
  set -e
  elapsed=$(( $(date +%s) - started ))
  if [ "$code" -eq 0 ]; then
    say "sshd 正常退出（用户停止了恢复模式）"
    exit 0
  fi
  say "sshd 退出 code=$code（存活 ${elapsed}s，第 $attempt 次）"
  if [ "$attempt" -ge 3 ]; then
    say "sshd 连续 3 次起不来 —— 保持沙箱存活，方便你从日志里排查"
    say "常见原因：端口 $PORT 被占用（应用面板可改端口）、/run/sshd 不可写、rootfs 已满"
    while :; do sleep 3600; done
  fi
  sleep 2
done
